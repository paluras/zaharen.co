const INSTRUMENT_ORDER = [
  "sax",
  "trumpet",
  "guitar",
  "piano",
  "rhodes",
  "synth",
  "synths",
  "synthbass",
  "bass",
  "drums",
];
const KEYBOARDS = new Set(["piano", "rhodes", "synth", "synths", "synthbass"]);

// Fixed order: winds, guitar, keys, bass, drums. All keyboards share one row.
function lineupRows(lineup) {
  const players = {};
  lineup.forEach(([who, instruments]) => {
    instruments.forEach((instrument) => {
      players[instrument] = [...(players[instrument] || []), who];
    });
  });

  const rows = [];
  const keys = { instruments: [], people: [] };
  const placeKeys = () => {
    if (keys.instruments.length && !rows.includes(keys)) rows.push(keys);
  };

  INSTRUMENT_ORDER.forEach((instrument) => {
    if (!players[instrument]) return;
    if (KEYBOARDS.has(instrument)) {
      keys.instruments.push(instrument);
      keys.people.push(...players[instrument]);
      return;
    }
    if (instrument === "bass" || instrument === "drums") placeKeys();
    rows.push({ instruments: [instrument], people: players[instrument] });
  });
  placeKeys();

  return rows.map((row) => ({
    instruments: row.instruments,
    people: [...new Set(row.people)].map((key) => musicians[key]).join(", "),
  }));
}

